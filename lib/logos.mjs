// Brand logos as terminal art. No dependencies: the pixel data below is generated once from the real
// image files by admin/logos.cjs (sharp), this file only paints it.
// Each logo is a grid of pixels, two per terminal cell (▀ with fg = top pixel, bg = bottom pixel).
// Pixel chars: '0' empty, '1'-'9' coverage of color 0, 'b'-'j' coverage of color 1.

// ── 256-color helpers ─────────────────────────────────────────────────────────────────────────────
const CUBE = [0, 95, 135, 175, 215, 255];
const cache = new Map();
export function to256([r, g, b]) {
  const key = (r << 16) | (g << 8) | b;
  let v = cache.get(key);
  if (v !== undefined) return v;
  const q = (x) => CUBE.reduce((bi, cv, i) => (Math.abs(cv - x) < Math.abs(CUBE[bi] - x) ? i : bi), 0);
  const [ri, gi, bi] = [q(r), q(g), q(b)];
  const cubeD = (CUBE[ri] - r) ** 2 + (CUBE[gi] - g) ** 2 + (CUBE[bi] - b) ** 2;
  const avg = (r + g + b) / 3;
  const gi2 = Math.max(0, Math.min(23, Math.round((avg - 8) / 10)));
  const gv = 8 + gi2 * 10;
  const greyD = (gv - r) ** 2 + (gv - g) ** 2 + (gv - b) ** 2;
  v = greyD < cubeD ? 232 + gi2 : 16 + 36 * ri + 6 * gi + bi;
  cache.set(key, v);
  return v;
}

export const CARD_BG = [28, 28, 28]; // the dark card the logos sit on (works on light and dark terminals)

// ── canvas: place logos at pixel offsets, then paint as cells ─────────────────────────────────────
// items: [{ name, x (cells), y (cells) }]. Returns one string per cell row (with escape codes).
// opts.k(x, y, W, H) -> 0..1 brightness per pixel (for the fade/wipe animation).
// opts.ascii: paint with background-colored spaces only (pure ASCII, half the vertical resolution).
export function paint(items, cols, rows, { k = () => 1, ascii = false, bg = CARD_BG } = {}) {
  const W = cols, H = rows * 2;
  const px = Array.from({ length: H }, () => new Array(W).fill(null));
  for (const it of items) {
    const L = LOGO_DATA[it.name];
    for (let y = 0; y < L.h; y++) for (let x = 0; x < L.w; x++) {
      const ch = L.rows[y].charCodeAt(x);
      if (ch === 48) continue;
      const ci = ch >= 97 ? 1 : 0, lvl = (ch >= 97 ? ch - 97 : ch - 48) / 9;
      const X = it.x + x, Y = it.y * 2 + y;
      if (X < 0 || X >= W || Y < 0 || Y >= H) continue;
      px[Y][X] = [L.colors[ci], lvl];
    }
  }
  const color = (p, x, y) => {
    if (!p) return bg;
    const t = p[1] * Math.max(0, Math.min(1, k(x, y, W, H)));
    return bg.map((b, j) => Math.round(b + (p[0][j] - b) * t));
  };
  const lines = [];
  for (let r = 0; r < rows; r++) {
    let s = "", last = "";
    for (let x = 0; x < W; x++) {
      const top = color(px[r * 2][x], x, r * 2), bot = color(px[r * 2 + 1][x], x, r * 2 + 1);
      let seq, ch;
      if (ascii) { seq = `48;5;${to256(top.map((v, j) => (v + bot[j]) >> 1))}`; ch = " "; }
      else { seq = `38;5;${to256(top)};48;5;${to256(bot)}`; ch = "▀"; }
      if (seq !== last) { s += `\x1b[${seq}m`; last = seq; }
      s += ch;
    }
    lines.push(s + "\x1b[0m");
  }
  return lines;
}

